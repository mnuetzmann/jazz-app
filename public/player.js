const LISTEN_MS = 20000;
const INTRO_EVERY = 2; // host introduces songs 1, 3, 5 of each set (1 = every song)

const $ = (id) => document.getElementById(id);
const audio = new Audio();
let categories = [];   // the styles of the current collection (what the screen offers)
let library = [];      // every style with songs, whatever its collection
let collections = [];  // [{ id, label }]; id '' is the main one (styles directly in music/)
let collection = '';
try { collection = localStorage.getItem('collection') || ''; } catch { /* storage blocked: the main collection */ }
// Play mode (settings): 'ask' = pick a style and be asked what next; 'shuffle' = random songs from the whole
// library; 'auto' = random songs from the styles scheduled for this time of day (schedule.json).
let mode = 'ask';
let quiet = false; // settings: no spoken announcements at all
try {
  mode = localStorage.getItem('mode') || (localStorage.getItem('shuffle') === '1' ? 'shuffle' : 'ask');
  quiet = localStorage.getItem('quiet') === '1';
} catch { /* storage blocked: defaults */ }
const continuous = () => mode !== 'ask';
let schedule = { slots: [], playlists: [] };
let unanswered = 0; // questions in a row that nobody answered; after two the station stops asking
const quietNow = () => quiet || unanswered >= 2;
let lastSpoke = Date.now(); // for the station ID
let lastHour = ''; // the hour already announced ('2026-10-16 14')
let queueSlot = ''; // which schedule slot the current auto queue was built for
let current = null;
let queue = [];
let playedInSet = 0;
let phase = 'idle'; // idle | playing | asking
let recognition = null;
let askTimer = null;
let recentTitles = [];
let recentGroups = []; // songs (not takes) played lately; a new shuffle pass does not open with the last one
let askPrefetch = null;
let plan = null; // the set being played: { cat, queue, intros }
let trackSeq = 0;
let introActive = false;

const shuffle = (a) => a.map((v) => [Math.random(), v]).sort((x, y) => x[0] - y[0]).map((p) => p[1]);
const label = (c) => c.label;

function post(msg) {
  fetch('/api/send', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(msg) }).catch(() => {});
}

function publish() {
  document.body.dataset.phase = phase;
  post({
    type: 'state', phase, category: current && current.id,
    track: phase === 'playing' ? $('now').textContent : '',
    categories: categories.map((c) => ({ id: c.id, label: c.label, thumb: c.thumb })),
  });
}

function setStatus(text) { $('status').textContent = text; }

// ---- announcer voice (ElevenLabs, generated by the server) ---------------
const voice = new Audio();
let voiceToken = 0;

let voiceName = '';
try { voiceName = localStorage.getItem('voice') || ''; } catch { /* storage blocked: default voice */ }

async function setupVoices() {
  const { voices } = await fetch('/api/voices').then((r) => r.json()).catch(() => ({ voices: [] }));
  if (!voices.includes(voiceName)) voiceName = voices[0] || '';
  const pickers = document.querySelectorAll('.voice-pick');
  pickers.forEach((sel) => {
    sel.hidden = voices.length < 2;
    sel.innerHTML = '';
    voices.forEach((v) => sel.add(new Option(v, v)));
    sel.value = voiceName;
    sel.onchange = () => {
      voiceName = sel.value;
      pickers.forEach((o) => { o.value = voiceName; });
      try { localStorage.setItem('voice', voiceName); } catch { /* not saved */ }
    };
  });
}
setupVoices();

async function fetchAnnouncement(body) {
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), 12000);
  try {
    const res = await fetch('/api/announce', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ ...body, voice: voiceName }), signal: ctl.signal,
    });
    if (!res.ok) throw new Error((await res.json().catch(() => ({}))).error || 'The announcer is unavailable right now.');
    return URL.createObjectURL(await res.blob());
  } finally {
    clearTimeout(timer);
  }
}

// Resolves when the announcement ends. Never rejects: if the voice is
// unavailable the announcement is skipped and the station carries on.
function say(body, prefetched) {
  if (quietNow()) return Promise.resolve();
  lastSpoke = Date.now();
  const token = ++voiceToken;
  return (prefetched || fetchAnnouncement(body)).then((url) => new Promise((resolve) => {
    if (token !== voiceToken) { URL.revokeObjectURL(url); return resolve(); }
    const done = () => { voice.onended = voice.onerror = null; URL.revokeObjectURL(url); resolve(); };
    voice.onended = voice.onerror = done;
    voice.src = url;
    voice.play().catch(done);
  })).catch((err) => notice(err.name === 'AbortError' ? 'The announcer is taking too long.' : err.message));
}

// A short, quiet note when the announcer cannot speak. The reason shows once, not on every song;
// the technical detail is in the server's log. Music carries on regardless.
const noticed = new Map();
function notice(text) {
  const last = noticed.get(text) || 0;
  if (Date.now() - last < 10 * 60 * 1000) return;
  noticed.set(text, Date.now());
  const el = $('notice');
  el.textContent = `${text} The music continues.`;
  el.classList.add('on');
  clearTimeout(notice.timer);
  notice.timer = setTimeout(() => el.classList.remove('on'), 9000);
}

function stopVoice() {
  voiceToken++;
  voice.pause();
  if (voice.onended) voice.onended();
}

// ---- speech in -----------------------------------------------------------
const MIC_HELP = {
  'not-allowed': 'The microphone is blocked. Click the lock icon in the address bar and allow the microphone; also check macOS System Settings > Privacy & Security > Microphone > Chrome.',
  'service-not-allowed': 'The microphone is blocked. Click the lock icon in the address bar and allow the microphone; also check macOS System Settings > Privacy & Security > Microphone > Chrome.',
  'audio-capture': 'No microphone was found.',
  'network': "Chrome's speech service could not be reached (it needs an internet connection).",
};
let micFatal = false;

function listen(onText) {
  const SR = window.SpeechRecognition || window.webkitSpeechRecognition;
  if (!SR) { $('heard').textContent = 'Voice input needs Chrome. Tap a choice instead.'; return; }
  if (!window.isSecureContext) {
    $('heard').textContent = `The mic only works at http://localhost:${location.port} on this computer, not at ${location.host}. Tap a choice instead.`;
    return;
  }
  stopListening();
  micFatal = false;
  const r = new SR();
  recognition = r;
  r.lang = 'en-US';
  r.interimResults = true; // show words as they are heard, to see where it fails
  r.maxAlternatives = 3;
  r.onstart = () => { $('heard').textContent = '🎤 Starting…'; };
  r.onaudiostart = () => { $('heard').textContent = ''; }; // the mic is on: clear "Starting…", say nothing more
  r.onsoundstart = () => { $('heard').textContent = '🎤 Hearing sound…'; };
  r.onspeechstart = () => { $('heard').textContent = '🎤 Hearing speech…'; };
  r.onnomatch = () => { $('heard').textContent = "Heard something but couldn't make out words. Try again."; };
  r.onresult = (e) => {
    const res = e.results[e.results.length - 1];
    if (!res.isFinal) { $('heard').textContent = `Hearing: "${res[0].transcript}"`; return; }
    const text = Array.from(res).map((x) => x.transcript).join(' | ');
    $('heard').textContent = `Heard: "${res[0].transcript}"`;
    onText(text.toLowerCase());
  };
  r.onerror = (e) => {
    if (e.error === 'no-speech' || e.error === 'aborted') return; // normal; onend restarts
    micFatal = true; // do not retry a blocked or missing mic in a loop
    $('heard').textContent = `${MIC_HELP[e.error] || `Mic error: ${e.error}.`} Tap a choice instead.`;
  };
  r.onend = () => { if (!micFatal && phase === 'asking' && recognition === r) setTimeout(() => { if (recognition === r) { try { r.start(); } catch {} } }, 300); };
  try { r.start(); } catch (err) { $('heard').textContent = `Could not start the microphone (${err.message}).`; }
}

// What the listener said (or typed on the phone remote).
function handleReply(text) {
  const c = matchCategory(text);
  if (c) choose(c);
  else $('heard').textContent = `Heard "${text.split(' | ')[0]}", but no style matched. Try again, or tap one.`;
}

function stopListening() {
  if (recognition) { const r = recognition; recognition = null; try { r.abort(); } catch {} }
}

function matchCategory(text) {
  if (/\b(same|again|keep (it|them|going)|more of (this|that|the same))\b/.test(text)) return current;
  if (/\b(surprise|anything|random|you choose|your choice)\b/.test(text)) {
    return shuffle(categories.filter((c) => c !== current))[0] || current;
  }
  let best = null, bestScore = 0;
  for (const c of categories) {
    const words = c.label.toLowerCase().split(/\s+/).filter((w) => w.length > 2);
    const score = words.filter((w) => text.includes(w)).length / words.length;
    if (score > bestScore) { best = c; bestScore = score; }
  }
  return best;
}

// ---- playback ------------------------------------------------------------
// One randomly chosen take of each song in the style (never both versions in a set).
function onePerSong(cat) {
  const byGroup = new Map();
  for (const t of cat.tracks) {
    if (!byGroup.has(t.group)) byGroup.set(t.group, []);
    byGroup.get(t.group).push(t);
  }
  return [...byGroup.values()].map((takes) => ({ ...takes[Math.floor(Math.random() * takes.length)], cat }));
}

// Every song in the style, in random order.
const buildQueue = (cat) => shuffle(onePerSong(cat));

// ---- schedule (Auto mode) -------------------------------------------------
const minutesOf = (hhmm) => { const [h, m] = String(hhmm).split(':').map(Number); return (h || 0) * 60 + (m || 0); };
function slotNow() {
  const d = new Date(), m = d.getHours() * 60 + d.getMinutes();
  return schedule.slots.find((sl) => {
    const f = minutesOf(sl.from), t = minutesOf(sl.to);
    return f <= t ? m >= f && m < t : m >= f || m < t; // a slot may run past midnight
  }) || null;
}
// The styles allowed now: those the slot lists (a collection folder or a style); all of them if none match.
const matching = (picks) => library.filter((c) => (picks || []).some((p) => c.id === p || c.id.startsWith(p + '/') || c.collection === p));
const playlistNow = () => (mode.startsWith('list:') ? schedule.playlists.find((l) => 'list:' + l.name === mode) : null);
function poolNow() {
  const sl = mode === 'auto' ? slotNow() : null;
  const list = playlistNow();
  const hit = sl ? matching(sl.pick) : list ? matching(list.pick) : library;
  return hit.length ? hit : library;
}

// The Play mode menu: the built-in modes, then each playlist from schedule.json (e.g. "Band Leaders").
function setupModes() {
  const sel = $('mode');
  sel.innerHTML = '';
  [['ask', 'Ask me what to play'], ['shuffle', 'Shuffle all music'], ['auto', 'Auto (by time of day)'],
   ...schedule.playlists.map((l) => ['list:' + l.name, l.name])].forEach(([v, t]) => sel.add(new Option(t, v)));
  if (!playlistNow() && mode.startsWith('list:')) mode = 'ask'; // that playlist is gone
  sel.value = mode;
  reflectMode();
}

// Shuffle, Auto and playlists: every song from every style in the pool goes into one list, which is shuffled
// and played through; when it runs out, the whole list is shuffled again. So each song plays once per pass,
// and every style is heard, in proportion to how many songs it has. (Auto rebuilds it when the time slot changes.)
function buildContinuousQueue() {
  queueSlot = mode === 'auto' ? (slotNow() || {}).name || '' : '';
  const list = shuffle(poolNow().flatMap(onePerSong));
  // a new pass should not open with the song that has just played
  if (list.length > 1 && list[0].group === recentGroups[recentGroups.length - 1]) [list[0], list[1]] = [list[1], list[0]];
  return list;
}

// Build a set and start fetching its first introduction right away, so it can
// download while the "coming right up" line is still being spoken.
function prepareSet(cat) {
  const next = { cat, queue: buildQueue(cat), intros: {} };
  introFor(next, 0);
  return next;
}

function introFor(p, i) {
  if (quietNow() || i >= p.queue.length || i % INTRO_EVERY !== 0) return null;
  if (!p.intros[i]) {
    p.intros[i] = fetchAnnouncement({
      kind: 'intro', category: (p.queue[i].cat || p.cat).id, url: p.queue[i].url, // in Shuffle / Auto / playlists each song has its own style
      previous: i > 0 ? p.queue[i - 1].url : undefined, // the song that just finished
    });
    p.intros[i].catch(() => {});
  }
  return p.intros[i];
}

// The radio touches between songs: "It's nine o'clock..." soon after the top of the hour, and a short
// station ID if the station has been silent for 40 minutes. Returns true if something was said.
async function stationSpot(seq) {
  if (quietNow()) return false;
  const now = new Date(), key = `${now.toDateString()} ${now.getHours()}`;
  let body = null;
  if (key !== lastHour) {
    lastHour = key;
    if (now.getMinutes() < 20) body = { kind: 'hour', hour: now.getHours() }; // not a time check long after the hour
  }
  if (!body && Date.now() - lastSpoke > 40 * 60 * 1000) body = { kind: 'stationid' };
  if (!body) return false;
  introActive = true;
  await say(body);
  introActive = false;
  return seq === trackSeq;
}

function startSet(next) {
  if (continuous()) setMode('ask'); // picking a style ends Shuffle / Auto
  stopListening();
  clearTimeout(askTimer);
  plan = next;
  current = next.cat;
  stage.setCategory(next.cat.id, next.cat.tracks.map((t) => t.cover));
  queue = next.queue;
  playedInSet = 0;
  $('choices').innerHTML = '';
  $('prompt').textContent = '';
  $('speak').hidden = true;
  $('heard').textContent = '';
  nextTrack();
}

async function nextTrack() {
  stopVoice();
  audio.pause();
  introActive = false;
  $('pause').textContent = 'Pause';
  const seq = ++trackSeq;
  if (continuous() && library.length && (playedInSet >= queue.length || (mode === 'auto' && queueSlot !== ((slotNow() || {}).name || '')))) {
    newList(); // never runs out, and follows the clock in Auto
    playedInSet = 0;
  }
  if (playedInSet >= queue.length) {
    if (quietNow() && current) return startSet(prepareSet(current)); // no questions: another set of the same style
    return askNext();
  }
  const i = playedInSet++;
  const t = queue[i];
  phase = 'playing';
  if (continuous() && (!current || t.cat.id !== current.id)) { // each song can come from a different style
    current = t.cat;
    stage.setCategory(current.id, current.tracks.map((x) => x.cover));
  }
  const slot = mode === 'auto' ? slotNow() : null;
  const list = playlistNow();
  setStatus(list ? `${list.name} · ${label(current)}` : mode === 'shuffle' ? `Shuffle · ${label(current)}` : mode === 'auto' ? `Auto${slot ? ` · ${slot.name}` : ''} · ${label(current)}` : `${label(current)}`);
  $('now').textContent = t.title;
  $('set').textContent = list ? list.name : mode === 'shuffle' ? 'Shuffle' : mode === 'auto' ? 'Auto' : `Song ${playedInSet} of ${queue.length}`;
  $('pause').hidden = $('skip').hidden = $('change').hidden = false;
  stage.songStarted(t);
  publish();

  const spoken = await stationSpot(seq); // top-of-the-hour time check or a station ID, if due
  if (seq !== trackSeq) return;
  const intro = spoken ? null : introFor(plan, i);
  if (intro) {
    introActive = true;
    await say({ kind: 'intro' }, intro);
    if (seq !== trackSeq) return; // skipped or replaced while the host was talking
    introActive = false;
  }

  recentTitles.push(t.url);
  recentTitles = recentTitles.slice(-60);
  recentGroups.push(t.group);
  recentGroups = recentGroups.slice(-60);
  audio.src = t.url;
  stage.feature();
  audio.play().catch((e) => {
    if (e.name === 'AbortError') return; // a newer track replaced this one
    $('heard').textContent = e.name === 'NotAllowedError'
      ? 'Chrome blocked playback. Click anywhere on this page, or press Try again.'
      : `Could not play "${t.title}" (${e.name}: ${e.message}).`;
    if (e.name === 'NotAllowedError') giveUp('Chrome blocked audio.');
  });
  introFor(plan, i + 1); // fetch the next introduction while this song plays
  if (!continuous() && !quietNow() && playedInSet === queue.length) { askPrefetch = fetchAnnouncement({ kind: 'ask', current: current.id, collection }); askPrefetch.catch(() => {}); }
}

async function askNext() {
  phase = 'asking';
  $('now').textContent = '';
  $('set').textContent = '';
  $('pause').hidden = $('skip').hidden = $('change').hidden = true;
  stage.songEnded();
  setStatus('What would you like to hear next?');
  showChoices();
  $('speak').hidden = false;
  publish();
  const prefetched = askPrefetch;
  askPrefetch = null;
  if (prefetched) prefetched.catch(() => {});
  await say({ kind: 'ask', current: current.id, collection }, prefetched);
  if (phase !== 'asking') return;
  listen(handleReply);
  askTimer = setTimeout(() => {
    if (phase === 'asking') { unanswered++; choose(shuffle(categories.filter((c) => c !== current))[0] || current, true); }
  }, LISTEN_MS);
}

function showChoices() {
  const box = $('choices');
  box.innerHTML = '';
  box.style.setProperty('--n', categories.length); // so the stack of buttons shares the screen height
  $('prompt').textContent = 'What would you like to hear next?';
  for (const c of categories) {
    const b = document.createElement('button');
    if (c.thumb) {
      b.className = 'tile' + (current && c.id === current.id ? ' current' : '');
      b.style.backgroundImage = `url("${c.thumb}")`;
      const name = document.createElement('span');
      name.className = 'name';
      name.textContent = c.label;
      b.append(name);
    } else {
      b.textContent = c.label; // a style without a picture stays a plain button
    }
    b.setAttribute('aria-label', c.label);
    b.onclick = () => choose(c);
    b.style.setProperty('--i', box.children.length); // its place in the stack, for the stagger
    box.appendChild(b);
  }
  const panel = $('panel');
  panel.classList.remove('reveal'); void panel.offsetWidth; // so the slide plays again every time they appear
  panel.classList.add('reveal');
}

async function choose(cat, auto = false) {
  if (!auto) unanswered = 0;
  if (phase === 'asking') {
    stopListening();
    clearTimeout(askTimer);
    stopVoice();
    phase = 'idle';
    setStatus(`Coming up: ${label(cat)}`);
    const next = prepareSet(cat);
    await say({ kind: auto ? 'auto' : 'chosen', category: cat.id });
    return startSet(next);
  }
  startSet(prepareSet(cat));
}

// ---- wiring --------------------------------------------------------------
audio.addEventListener('ended', nextTrack);
let failStreak = 0;
audio.addEventListener('playing', () => { failStreak = 0; });
audio.addEventListener('error', () => {
  if (phase !== 'playing') return;
  const err = audio.error;
  $('heard').textContent = `Could not play "${$('now').textContent}" (media error ${err ? err.code : '?'}${err && err.message ? `: ${err.message}` : ''}).`;
  if (++failStreak >= 3) return retryLater('Playback keeps failing.');
  setTimeout(nextTrack, 500);
});

// When songs will not play, do not skip through the whole library: wait, then try again, a little
// longer each time (up to five minutes). The music comes back by itself.
let retryDelay = 30000, retryTimer = null;
function retryLater(reason) {
  clearTimeout(retryTimer);
  phase = 'idle';
  stage.songEnded();
  trackSeq++;
  audio.pause();
  failStreak = 0;
  $('pause').hidden = $('skip').hidden = true;
  setStatus(`${reason} Trying again in ${Math.round(retryDelay / 1000)} seconds.`);
  publish();
  retryTimer = setTimeout(() => { retryDelay = Math.min(retryDelay * 2, 300000); nextTrack(); }, retryDelay);
}
audio.addEventListener('playing', () => { retryDelay = 30000; });

// A song that is "playing" but not moving (a stalled file or a network drive that went away) is skipped.
let lastPos = -1, frozen = 0;
setInterval(() => {
  if (phase !== 'playing' || introActive || audio.paused || audio.ended) { frozen = 0; lastPos = -1; return; }
  if (audio.currentTime === lastPos) { if (++frozen >= 3) { frozen = 0; failStreak++; failStreak >= 3 ? retryLater('Playback stalled.') : nextTrack(); } }
  else { frozen = 0; lastPos = audio.currentTime; }
}, 5000);

// Stop instead of skipping through the whole library when songs will not play.
function giveUp(reason) {
  phase = 'idle';
  stage.songEnded();
  trackSeq++;
  audio.pause();
  $('pause').hidden = $('skip').hidden = $('change').hidden = true;
  $('start').hidden = false;
  $('start').textContent = 'Try again';
  setStatus(`${reason} See the message below, then press Try again.`);
  publish();
}

function togglePause() {
  const el = introActive ? voice : audio;
  if (el.paused) { el.play(); $('pause').textContent = 'Pause'; } else { el.pause(); $('pause').textContent = 'Resume'; }
}
$('pause').onclick = togglePause;
$('skip').onclick = () => { unanswered = 0; if (phase === 'playing') nextTrack(); };

// Shuffle and Auto: songs keep coming, with no questions, until the mode is changed.
// A fresh shuffled list for Shuffle / Auto / a playlist, with its first introduction already on its way.
function newList() {
  queue = buildContinuousQueue();
  plan = { cat: null, queue, intros: {} };
  introFor(plan, 0);
}

function startContinuous(prebuilt = false) {
  stopListening();
  clearTimeout(askTimer);
  askPrefetch = null;
  if (!prebuilt) newList();
  playedInSet = 0;
  $('choices').innerHTML = '';
  $('prompt').textContent = '';
  $('speak').hidden = true;
  $('heard').textContent = '';
  nextTrack();
}

// Change Style and the collection picker only make sense when you choose the styles yourself ("Ask me"),
// so the stylesheet hides them whenever a playlist, Shuffle or Auto is playing.
function reflectMode() { document.body.classList.toggle('continuous-mode', continuous()); }

function setMode(m) {
  const was = mode;
  mode = m;
  reflectMode();
  $('mode').value = m;
  unanswered = 0;
  try { localStorage.setItem('mode', m); } catch { /* not saved */ }
  if (!library.length || m === was) return; // not started yet: applied when it starts
  if (continuous() && (phase === 'playing' || phase === 'asking')) {
    stopVoice();
    startContinuous();
  } else if (!continuous() && phase === 'playing') {
    queue = queue.slice(0, playedInSet); // let this song finish, then ask what next
  }
}
$('mode').value = mode;
$('mode').onchange = () => setMode($('mode').value);
$('quiet').checked = quiet;
$('quiet').onchange = () => {
  quiet = $('quiet').checked;
  try { localStorage.setItem('quiet', quiet ? '1' : '0'); } catch { /* not saved */ }
  if (quiet) stopVoice();
};

// Ask what to play next right now, without waiting for the set to finish.
function changeStyle() {
  unanswered = 0;
  setSettings(false);
  if (phase !== 'playing') return;
  trackSeq++; // cancel a pending introduction
  stopVoice();
  audio.pause();
  askNext();
}
$('change').onclick = changeStyle;

$('speak').onclick = () => { if (phase === 'asking') listen(handleReply); };

// ---- collections: groups of styles (a folder inside music/ whose sub-folders are the styles) ----
function applyCollection() {
  if (!collections.some((c) => c.id === collection)) collection = collections[0] ? collections[0].id : '';
  categories = library.filter((c) => c.collection === collection);
}

function setupCollections() {
  const sel = document.querySelector('.collection-pick');
  sel.hidden = collections.length < 2; // one collection: nothing to choose
  sel.innerHTML = '';
  collections.forEach((c) => sel.add(new Option(c.label, c.id)));
  sel.value = collection;
  sel.onchange = () => {
    collection = sel.value;
    try { localStorage.setItem('collection', collection); } catch { /* not saved */ }
    applyCollection();
    publish(); // the phone remote shows the new styles too
    if (phase === 'asking') showChoices();
  };
}

// Load the library and the schedule. Used at start and every half hour so new files are picked up.
async function loadLibrary() {
  const [res, sched] = await Promise.all([
    fetch('/api/library').then((r) => r.json()),
    fetch('/api/schedule').then((r) => r.json()).catch(() => ({ slots: [] })),
  ]);
  library = res.categories;
  collections = res.collections || [];
  schedule = {
    slots: Array.isArray(sched.slots) ? sched.slots : [],
    playlists: (Array.isArray(sched.playlists) ? sched.playlists : []).filter((l) => l && l.name && Array.isArray(l.pick)),
  };
  setupModes();
  applyCollection();
  if (current) current = library.find((c) => c.id === current.id) || current;
}
setInterval(() => { if (library.length) loadLibrary().then(() => { setupCollections(); }).catch(() => {}); }, 30 * 60 * 1000);

let beginning = false;
async function begin({ resumed = false } = {}) {
  if (beginning) return;
  beginning = true;
  $('start').hidden = true;
  try { localStorage.setItem('running', '1'); } catch { /* not saved */ }
  if (window.isSecureContext && navigator.mediaDevices && navigator.mediaDevices.getUserMedia) {
    navigator.mediaDevices.getUserMedia({ audio: true })
      .then((stream) => stream.getTracks().forEach((t) => t.stop()))
      .catch((err) => { $('heard').textContent = `Microphone not available (${err.name}). You can still tap your choices.`; });
  }
  for (;;) { // the server may still be starting (or restarting): keep trying instead of giving up
    try { await loadLibrary(); break; } catch {
      setStatus('Waiting for the music server…');
      await new Promise((r) => setTimeout(r, 10000));
    }
  }
  beginning = false;
  setupCollections();
  if (!categories.length) {
    setStatus('No songs found. Put MP3 files in music/<Collection>/<style>/ folders and reload.');
    $('start').hidden = false;
    return;
  }
  const n = new Date();
  lastHour = `${n.toDateString()} ${n.getHours()}`; // no time check right at the start
  lastSpoke = Date.now();
  const first = continuous() ? null : prepareSet(shuffle(categories)[0]);
  if (continuous()) newList(); // so the first introduction downloads while the welcome plays
  if (!resumed) await say({ kind: 'welcome' }); // a silent return after a reload or restart
  if (continuous()) startContinuous(true); else startSet(first);
}
$('start').onclick = () => begin();
// After a reload or a restart of the page, carry on by itself (Chrome may insist on one click first).
try { if (localStorage.getItem('running') === '1') begin({ resumed: true }); } catch { /* not saved */ }

const events = new EventSource('/events');
events.onopen = () => { if (library.length) publish(); }; // the server came back: tell the phone remote where we are
events.onmessage = (e) => {
  const m = JSON.parse(e.data);
  if (m.type !== 'state' && m.type !== 'hello') stage.wake();
  if (m.type === 'choose' && phase === 'asking') choose(categories.find((c) => c.id === m.category) || current);
  else if (m.type === 'choose' && phase === 'playing') { const c = categories.find((x) => x.id === m.category); if (c) startSet(prepareSet(c)); }
  else if (m.type === 'skip' && phase === 'playing') { unanswered = 0; nextTrack(); }
  else if (m.type === 'change') changeStyle();
  else if (m.type === 'pause' && phase === 'playing') togglePause();
  else if (m.type === 'say' && phase === 'asking' && m.text) handleReply(String(m.text).toLowerCase());
  else if (m.type === 'hello') publish();
};

